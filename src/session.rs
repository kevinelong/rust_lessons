//! A learner session as data — the input that phase 4 scoring is written against.
//!
//! Nothing here measures a learner: this module only *reads* a session that was already
//! recorded, so scoring can be developed, tested and argued about without a person present,
//! a window open, or a socket. The fixture checked in at
//! `fixtures/session-2026-11-07-synthetic.json` is one such session and is loaded by
//! `tests/session_fixture.rs`.
//!
//! # Why the answer is compared, not the verdict stored
//!
//! A recorded session says what the learner wrote and what the item wanted; whether that
//! was right is a *derived* fact ([`Attempt::is_correct`]), so the data cannot claim an
//! item was correct that its own text contradicts. That matters most for the wrong-then-right
//! pair: the pair is two rows with the same `section` and `prompt`, and the retry is provably
//! the same item rather than a second, similar one.
//!
//! The comparison is: trim, drop a pair of surrounding backticks, collapse runs of
//! whitespace to one space, then compare exactly. Whitespace inside an answer is not
//! meaningful (`2+3*4` and `2 + 3 * 4` are still different answers), and case *is*
//! meaningful — section 01 teaches that `Total` and `total` are two names.
//!
//! # The schema
//!
//! ```json
//! {
//!   "schema": 1,
//!   "session_id": "synthetic-2026-11-07-a",
//!   "learner": "synthetic-fixture",
//!   "synthetic": true,
//!   "started": "2026-11-07T08:40:00Z",
//!   "items": [
//!     {
//!       "section": "01",
//!       "prompt": "s01-q2",
//!       "mode": "retrieval",
//!       "attempt": 1,
//!       "answer": "var",
//!       "expected": "let",
//!       "ms": 6100
//!     }
//!   ]
//! }
//! ```
//!
//! * `section` — two digits, the same numbering as `src/section_NN_*.rs` and
//!   `problems/section_NN_*.md`, because that is the key every other artefact uses.
//! * `prompt` — the item's id inside its section (`s01-q2` is question 2 of section 01's
//!   retrieval check; `s01-parsons` is that section's Parsons problem).
//! * `mode` — `retrieval` for a question answered from memory, `recognition` for an item
//!   where the material is in front of the learner (a Parsons problem is answered by
//!   rearranging lines that are already given). Scoring reports the two separately: a
//!   learner who can recognise working code but not recall a name has a different problem
//!   from one who can do neither.
//! * `attempt` — 1-based, consecutive per `(section, prompt)`, in document order.
//! * `answer` / `expected` — what was written, and what the item wanted. For a Parsons
//!   problem both are the line numbers in the order the learner put them, comma-separated
//!   (`"12,5,9,11,7,6,8,2,1,3,4,10"`), because the exercise is an ordering, not a word.
//! * `ms` — time to answer, in milliseconds, whole numbers. A positive integer, because a
//!   zero would be a missing timing wearing a number's clothes.
//!
//! No timestamp per item: only the session's start is recorded, and durations are the
//! measured axis. Adding a per-item clock would invite a second, disagreeing timeline.

use serde::{Deserialize, Serialize};
use std::fs;
use std::path::Path;

use crate::SECTION_COUNT;

/// The schema this build reads. A session from the future is refused rather than
/// half-read.
pub const SCHEMA: u8 = 1;

/// How an item asked: from memory, or with the material in hand.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Mode {
    /// Answered from memory — the retrieval check generated by `cargo run --bin quiz`.
    Retrieval,
    /// Answered with the material visible — the Parsons problem generated by
    /// `cargo run --bin parsons`.
    Recognition,
}

impl Mode {
    /// The name the data uses, so a report can print what the JSON says.
    pub fn as_str(self) -> &'static str {
        match self {
            Mode::Retrieval => "retrieval",
            Mode::Recognition => "recognition",
        }
    }
}

/// One answer, with the time it took.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Attempt {
    /// Two-digit section number, as `src/section_NN_*.rs` names it.
    pub section: String,
    /// The item's id within the section.
    pub prompt: String,
    /// Retrieval or recognition.
    pub mode: Mode,
    /// 1-based, consecutive per `(section, prompt)`.
    pub attempt: u8,
    /// What the learner wrote.
    pub answer: String,
    /// What the item wanted.
    pub expected: String,
    /// Time to answer, milliseconds.
    pub ms: u64,
}

impl Attempt {
    /// Was this attempt right?
    ///
    /// Derived from `answer` and `expected` rather than stored, so the data cannot hold a
    /// verdict its own text contradicts.
    pub fn is_correct(&self) -> bool {
        normalise(&self.answer) == normalise(&self.expected)
    }

    /// The item this attempt belongs to: `(section, prompt)`.
    pub fn item(&self) -> (&str, &str) {
        (&self.section, &self.prompt)
    }

    /// Seconds to answer, to one decimal — the unit a report prints.
    pub fn seconds(&self) -> f64 {
        self.ms as f64 / 1000.0
    }
}

/// One learner session.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Session {
    /// Schema version; this build reads [`SCHEMA`].
    pub schema: u8,
    /// Identifies the session, and the file name it is stored under.
    pub session_id: String,
    /// Who sat it. `synthetic-fixture` means no person did.
    pub learner: String,
    /// True when no human produced the answers. A real session must say so.
    pub synthetic: bool,
    /// When the session began, RFC 3339, UTC.
    pub started: String,
    /// Every answer, in the order it was given.
    pub items: Vec<Attempt>,
}

impl Session {
    /// Read a session from JSON text.
    pub fn from_json_str(text: &str) -> Result<Self, String> {
        let session: Session = serde_json::from_str(text).map_err(|e| e.to_string())?;
        session.validate()?;
        Ok(session)
    }

    /// Read a session from a file. No network, no UI: a path in, data out.
    pub fn load(path: impl AsRef<Path>) -> Result<Self, String> {
        let path = path.as_ref();
        let text = fs::read_to_string(path)
            .map_err(|e| format!("{}: {e}", path.display()))?;
        Self::from_json_str(&text)
    }

    /// Does the session satisfy every rule the loader promises?
    ///
    /// The rules are the ones a score would silently misreport if broken: an attempt
    /// numbered from zero would look like a first try, a retry out of order would look
    /// like an improvement that never happened, a zero duration would average in as
    /// instant recall, and a section that does not exist could never be joined to the
    /// course.
    pub fn validate(&self) -> Result<(), String> {
        if self.schema != SCHEMA {
            return Err(format!(
                "session {} declares schema {}, this build reads {SCHEMA}",
                self.session_id, self.schema
            ));
        }
        if self.session_id.trim().is_empty() {
            return Err("session has no id".into());
        }
        if self.started.trim().is_empty() {
            return Err(format!("session {} has no start time", self.session_id));
        }
        if self.items.is_empty() {
            return Err(format!("session {} records no attempts", self.session_id));
        }
        for item in &self.items {
            let digits = item.section.len() == 2 && item.section.chars().all(|c| c.is_ascii_digit());
            let in_course = digits
                && item
                    .section
                    .parse::<u8>()
                    .map(|n| (1..=SECTION_COUNT).contains(&n))
                    .unwrap_or(false);
            if !in_course {
                return Err(format!(
                    "attempt on {:?}: section {:?} is not one of the {SECTION_COUNT} sections",
                    item.prompt, item.section
                ));
            }
            if item.prompt.trim().is_empty() {
                return Err(format!("section {} has an attempt with no prompt id", item.section));
            }
            if item.expected.trim().is_empty() {
                return Err(format!("{} has no expected answer", item.prompt));
            }
            if item.ms == 0 {
                return Err(format!("{} records a zero time to answer", item.prompt));
            }
        }
        // Attempt numbers run 1, 2, 3 … per item, in document order. A wrong-then-right
        // pair is only legible if the retry is provably the same item's next attempt.
        let mut seen: std::collections::HashMap<(&str, &str), u8> = std::collections::HashMap::new();
        for item in &self.items {
            let key = item.item();
            let next = seen.get(&key).copied().unwrap_or(0) + 1;
            if item.attempt != next {
                return Err(format!(
                    "{} / {} is attempt {}, expected attempt {next}",
                    item.section, item.prompt, item.attempt
                ));
            }
            seen.insert(key, next);
        }
        Ok(())
    }

    /// The sections this session touched, sorted, each once.
    pub fn sections(&self) -> Vec<&str> {
        let mut sections: Vec<&str> = self.items.iter().map(|a| a.section.as_str()).collect();
        sections.sort_unstable();
        sections.dedup();
        sections
    }

    /// Every attempt at one item, in the order given.
    pub fn attempts_for(&self, section: &str, prompt: &str) -> Vec<&Attempt> {
        self.items
            .iter()
            .filter(|a| a.section == section && a.prompt == prompt)
            .collect()
    }
}

/// The comparison [`Attempt::is_correct`] uses: trim, drop surrounding backticks, collapse
/// runs of whitespace to one space. Case and inner spacing are left alone.
fn normalise(text: &str) -> String {
    let mut trimmed = text.trim();
    if let Some(rest) = trimmed.strip_prefix('`') {
        trimmed = rest;
    }
    if let Some(rest) = trimmed.strip_suffix('`') {
        trimmed = rest;
    }
    trimmed.split_whitespace().collect::<Vec<_>>().join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn attempt(answer: &str, expected: &str, ms: u64, n: u8) -> Attempt {
        Attempt {
            section: "01".into(),
            prompt: "s01-q2".into(),
            mode: Mode::Retrieval,
            attempt: n,
            answer: answer.into(),
            expected: expected.into(),
            ms,
        }
    }

    #[test]
    fn a_verdict_comes_from_the_text_not_a_flag() {
        assert!(attempt("let", "let", 2400, 2).is_correct());
        assert!(!attempt("var", "let", 6100, 1).is_correct());
    }

    #[test]
    fn whitespace_and_quotes_are_not_part_of_an_answer() {
        assert!(attempt("  `let`  ", "let", 1, 1).is_correct());
        assert!(attempt("2 +  3 * 4", "2 + 3 * 4", 1, 1).is_correct());
    }

    #[test]
    fn inner_spacing_and_case_are_part_of_an_answer() {
        // Section 01 teaches that `Total` and `total` are two names, so folding case
        // would score a wrong answer right.
        assert!(!attempt("total", "Total", 1, 1).is_correct());
        assert!(!attempt("2+3*4", "2 + 3 * 4", 1, 1).is_correct());
    }

    #[test]
    fn a_retry_out_of_order_is_refused() {
        let mut session = Session {
            schema: SCHEMA,
            session_id: "s".into(),
            learner: "synthetic-fixture".into(),
            synthetic: true,
            started: "2026-11-07T08:40:00Z".into(),
            items: vec![attempt("var", "let", 6100, 1), attempt("let", "let", 2400, 3)],
        };
        assert!(session.validate().is_err());
        session.items[1].attempt = 2;
        assert!(session.validate().is_ok());
    }

    #[test]
    fn a_zero_duration_is_refused() {
        let session = Session {
            schema: SCHEMA,
            session_id: "s".into(),
            learner: "synthetic-fixture".into(),
            synthetic: true,
            started: "2026-11-07T08:40:00Z".into(),
            items: vec![attempt("let", "let", 0, 1)],
        };
        assert!(session.validate().is_err());
    }
}
