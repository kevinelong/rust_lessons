# Regenerate the narrated videos for a set of sections, and optionally publish them.
#
#   powershell -NoProfile -File tools/release-videos.ps1 -Sections 7,8 -SkipPublish
#   powershell -NoProfile -File tools/release-videos.ps1 -Tag v0.14.0
#
# Each section goes through the same four steps the docs describe, in this order, because
# `narrate` wipes the section directory: narrate -> tts -> screenshots -> mux. Skipping the
# tts step produces a valid MP4 of silent 2.2 s slides, which is why it is not optional here.
param(
    # "all", "7" or "7,8,11". Parse it here: -File passes a comma list through as one
    # string, so [int[]] binding turned 12,13 into 1213.
    [string] $Sections = "all",
    [string] $Tag = "",
    [string] $Python = "$env:USERPROFILE\.ttsvenv\Scripts\python.exe",
    [string] $Chrome = "C:\Program Files\Google\Chrome\Application\chrome.exe",
    [string] $Notes = "Regenerated by tools/release-videos.ps1 - see the source repository for what changed.",
    [switch] $SkipPublish
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
Set-Location $root
$video = Join-Path $root "out\video"

if (-not (Test-Path $Chrome)) { throw "chrome not found: $Chrome" }
if (-not (Test-Path $Python)) { throw "python (kokoro-onnx venv) not found: $Python" }

# Must track rust_lessons::SECTION_COUNT; the script fails loudly if a section is missing.
$sectionCount = 21
$list = if ($Sections -eq "all") {
    1..$sectionCount
} else {
    $Sections -split ',' | ForEach-Object { [int]$_.Trim() }
}
$started = Get-Date
foreach ($n in $list) {
    $id = "{0:D2}" -f $n
    $dir = Join-Path $video "section_$id"
    Write-Host "[$id] narrate"
    & cargo run --quiet --bin narrate -- $n | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "narrate failed for section $id" }

    Write-Host "[$id] tts (kokoro)"
    Push-Location $dir
    try {
        & $Python "tts.py" | Out-Null
        if ($LASTEXITCODE -ne 0) { throw "tts failed for section $id" }
        $wavs = (Get-ChildItem "narration\*.wav" -ErrorAction SilentlyContinue).Count
        if ($wavs -lt 1) { throw "no narration for section $id - refusing to mux silence" }

        Write-Host "[$id] screenshots ($wavs narration files)"
        New-Item -ItemType Directory -Force -Path "slides" | Out-Null
        $cwdFwd = (Get-Location).Path -replace '\\', '/'
        foreach ($slide in Get-ChildItem "slide_*.html" | Sort-Object Name) {
            $name = $slide.BaseName + ".png"
            $out = "slides\$name"
            $url = "file:///" + ($slide.FullName -replace '\\', '/')
            # Chrome writes a benign extension-registry warning to stderr, and with
            # $ErrorActionPreference = Stop PowerShell treats native stderr as terminating.
            $eap = $ErrorActionPreference
            $ErrorActionPreference = "Continue"
            & $Chrome --headless=new --disable-gpu --hide-scrollbars --window-size=1600,900 `
                "--screenshot=$cwdFwd/$out" $url 2>&1 | Out-Null
            $ErrorActionPreference = $eap
            if (-not (Test-Path $out)) { throw "screenshot failed: $out" }
        }

        Write-Host "[$id] mux"
        & powershell -NoProfile -File "mux.ps1" | Out-Null
        if (-not (Test-Path "section_$id.mp4")) { throw "mux produced no MP4 for section $id" }
        $mb = [math]::Round((Get-Item "section_$id.mp4").Length / 1MB, 2)
        Write-Host "[$id] done: section_$id.mp4 ($mb MB)"
    }
    finally {
        Pop-Location
    }
}

$videos = Get-ChildItem (Join-Path $video "section_*\section_*.mp4")
$total = ($videos | Measure-Object Length -Sum).Sum / 1MB
Write-Host ("`n{0} videos, {1:N1} MB, {2:N0}s elapsed" -f $videos.Count, $total, ((Get-Date) - $started).TotalSeconds)

if ($SkipPublish -or [string]::IsNullOrWhiteSpace($Tag)) {
    Write-Host "not publishing (no -Tag, or -SkipPublish)"
    exit 0
}

# Publish: hashes next to the assets, then one release carrying all of them.
$stage = Join-Path $root "out\release-$Tag"
if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
New-Item -ItemType Directory -Path $stage | Out-Null
foreach ($v in $videos) { Copy-Item $v.FullName $stage }
$sums = foreach ($v in (Get-ChildItem "$stage\*.mp4")) {
    "{0}  {1}" -f (Get-FileHash $v.FullName -Algorithm SHA256).Hash.ToLower(), $v.Name
}
$sums | Set-Content -Path (Join-Path $stage "SHA256SUMS") -Encoding ascii

Write-Host "publishing $Tag with $($videos.Count) videos"
& gh release create $Tag --repo kevinelong/rust-lessons-releases --title "rust_lessons $Tag" `
    --notes $Notes `
    (Get-ChildItem "$stage\*.mp4" | ForEach-Object { $_.FullName }) (Join-Path $stage "SHA256SUMS")
if ($LASTEXITCODE -ne 0) { throw "gh release create failed" }
Write-Host "published $Tag"
